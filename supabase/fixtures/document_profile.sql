-- What the task's verification asks to read back:
select d.scl_doc_number, d.current_revision_id,
       (select count(*) from dcs.files f where f.revision_id = d.current_revision_id) as files
  from dcs.documents d
 where d.id in ('f3000000-0000-4000-8000-000000000001', 'f3000000-0000-4000-8000-000000000002')
 order by d.scl_doc_number;
